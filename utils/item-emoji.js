/** 分类兜底：名称认不出来时，至少跟分类一致（与后端预设分类 id 对齐） */
var CATEGORY_FALLBACK = {
  food: '🍱',
  beverage: '🥤',
  // 日用品泛指杂货，用篮子；🧴 是洗护瓶，只留给洗发水 / 面霜这类真装瓶的
  daily: '🧺',
  medicine: '💊',
  cosmetic: '💄',
  seasoning: '🧂',
  frozen: '🧊',
  other: '📦'
};

/** 关键字索引，模块加载时算一次：长度降序，同长度保持声明顺序 */
var INDEX = (function () {
  var pairs = [];
  RULES.forEach(function (rule) {
    rule[1].split(/\s+/).forEach(function (key) {
      if (key) pairs.push({ key: key, emoji: rule[0], order: pairs.length });
    });
  });
  pairs.sort(function (a, b) {
    if (b.key.length !== a.key.length) return b.key.length - a.key.length;
    return a.order - b.order;
  });
  return pairs;
})();

/**
 * 给一件物品挑 emoji。
 * @param {string} name 物品名称
 * @param {string} [category] 分类 id，名称认不出时兜底
 * @returns {string} 一个 emoji，永远有值
 */
function emojiFor(name, category) {
  var text = (name || '').trim();
  if (text) {
    for (var i = 0; i < INDEX.length; i++) {
      if (text.indexOf(INDEX[i].key) !== -1) return INDEX[i].emoji;
    }
  }
  return CATEGORY_FALLBACK[category] || CATEGORY_FALLBACK.other;
}

module.exports = {
  emojiFor: emojiFor,
  CATEGORY_FALLBACK: CATEGORY_FALLBACK
};
